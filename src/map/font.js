/** Text as the font can draw it: upper case, no accent. */
export function printable(text) {
  return String(text ?? '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase();
}

/**
 * Lit pixels of a character, as [column, row] pairs ([] for a blank).
 * @param {string} char one character of printable()
 */
export function glyphPixels(char) {
  const rows = GLYPHS[char];
  if (!rows) {
    return [];
  }
  const pixels = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < GLYPH_WIDTH; x++) {
      if (row[x] === '1') pixels.push([x, y]);
    }
  });
  return pixels;
}
